# CONTRIBUTION 3 — FINAL CONTROLLED SMOLLM2 BATCH PIPELINE
# V5 — HYBRID GENERATION
#
# KEY CHANGE FROM v4:
#   v1-v4 asked the LLM to generate all 3 sentences, including
#   Sentence 3 (Jaccard score + agreement wording + review
#   recommendation). Across two test rounds, Sentence 3 was the
#   ONLY recurring failure point (jaccard_value_missing_or_altered,
#   missing_manual_review) -- 100% of v4's fallbacks were this
#   single cause, concentrated in the low-agreement condition
#   where Sentence 3 has to satisfy 3 constraints at once.
#
#   FIX: Sentence 3 is no longer generated by the LLM at all.
#   It is always built deterministically in Python from the
#   evidence dict -- it's a template fill, not creative content,
#   so there's no reason to risk it on a 1.7B model.
#
#   The LLM's job shrinks to Sentences 1-2 only (prediction +
#   confidence, then the 3 SHAP features) -- the part it has
#   already been reliably getting right across prior test runs.
#
#   IMPORTANT: the evidence block shown to the LLM no longer
#   includes the Jaccard score or agreement category at all.
#   This prevents the model from referencing or paraphrasing
#   them on its own, which could otherwise create a contradiction
#   against the deterministic Sentence 3 (e.g. LLM says "moderate
#   agreement" while the deterministic sentence says "low
#   agreement"). Removing the information from its context makes
#   that failure mode structurally impossible, not just unlikely.
# ============================================================

