def run_batch_eval(
    evidence_records,
    llm,
    max_tokens=120,
    temperature=0.1,
    top_p=0.9,
    sample_size=None
):

    if sample_size is None:

        records = evidence_records

    else:

        records = (
            evidence_records[
                :sample_size
            ]
        )

    results = []

    print("=" * 80)
    print(
        "CONTRIBUTION 3 — SMOLLM2 V7 "
        "BOUNDED GENERATION"
    )
    print("=" * 80)

    print(
        "Records to evaluate:",
        len(records)
    )

    print(
        "max_tokens:",
        max_tokens
    )

    print(
        "temperature:",
        temperature
    )

    print(
        "top_p:",
        top_p
    )

    print("=" * 80)

    for i, evidence in enumerate(
        records,
        start=1
    ):

        start_time = time.time()

        raw_llm_output = ""
        cleaned_phrase = ""

        hard_reasons = []

        # ----------------------------------------------------
        # Deterministic Sentence 1
        # ----------------------------------------------------

        sentence_1 = (
            build_sentence_1(
                evidence
            )
        )

        # ----------------------------------------------------
        # LLM generation
        # ----------------------------------------------------

        try:

            prompt = build_prompt(
                evidence
            )

            response = (
                llm.create_chat_completion(
                    messages=[
                        {
                            "role": "system",
                            "content":
                                SYSTEM_PROMPT
                        },
                        {
                            "role": "user",
                            "content":
                                prompt
                        }
                    ],
                    max_tokens=max_tokens,
                    temperature=temperature,
                    top_p=top_p
                )
            )

            raw_llm_output = (
                response[
                    "choices"
                ][0][
                    "message"
                ][
                    "content"
                ].strip()
            )

            cleaned_phrase = (
                clean_output(
                    raw_llm_output
                )
            )

            (
                compliant,
                hard_reasons
            ) = check_llm_phrase(
                cleaned_phrase,
                evidence
            )

            if compliant:

                llm_phrase = (
                    cleaned_phrase
                )

                used_fallback = False

            else:

                llm_phrase = (
                    "with these supplied features "
                    "contributing to the model's "
                    "classification decision"
                )

                used_fallback = True

        except Exception as error:

            hard_reasons = [
                f"generation_error:{str(error)}"
            ]

            llm_phrase = (
                "with these supplied features "
                "contributing to the model's "
                "classification decision"
            )

            used_fallback = True

        # ----------------------------------------------------
        # Deterministic Sentence 2 assembly
        # ----------------------------------------------------

        sentence_2 = (
            build_sentence_2(
                evidence,
                llm_phrase
            )
        )

        # ----------------------------------------------------
        # Deterministic Sentence 3
        # ----------------------------------------------------

        sentence_3 = (
            build_sentence_3(
                evidence
            )
        )

        # ----------------------------------------------------
        # FINAL NARRATIVE
        # ----------------------------------------------------

        final_narrative = (
            sentence_1
            + " "
            + sentence_2
            + " "
            + sentence_3
        )

        elapsed = (
            time.time()
            - start_time
        )

        # ----------------------------------------------------
        # SAVE RESULT
        # ----------------------------------------------------

        results.append({

            "record_index":
                i - 1,

            "sample_index":
                evidence.get(
                    "Sample_Index",
                    i - 1
                ),

            "prediction":
                evidence["Predicted"],

            "confidence":
                evidence["Confidence"],

            "jaccard":
                evidence["Jaccard"],

            "agreement":
                evidence["Agreement"],

            "raw_llm_output":
                raw_llm_output,

            "cleaned_llm_phrase":
                cleaned_phrase,

            "hard_fail_reasons":
                "; ".join(
                    hard_reasons
                ),

            "used_fallback":
                used_fallback,

            "final_narrative":
                final_narrative,

            "generation_time_seconds":
                round(
                    elapsed,
                    3
                )
        })

        # ----------------------------------------------------
        # PROGRESS
        # ----------------------------------------------------

        status = (
            "FALLBACK"
            if used_fallback
            else "LLM OK"
        )

        print(
            f"[{i}/{len(records)}] "
            f"{status} | "
            f"Sample={evidence.get('Sample_Index', i-1)} | "
            f"Agreement={evidence['Agreement']}"
        )

        if hard_reasons:

            print(
                "    Reasons:",
                hard_reasons
            )

    # ========================================================
    # DATAFRAME
    # ========================================================

    results_df = pd.DataFrame(
        results
    )

    # ========================================================
    # SUMMARY
    # ========================================================

    print("\n" + "=" * 80)
    print(
        "CONTRIBUTION 3 — V7 BATCH SUMMARY"
    )
    print("=" * 80)

    total = len(
        results_df
    )

    fallback_count = int(
        results_df[
            "used_fallback"
        ].sum()
    )

    accepted_count = (
        total
        - fallback_count
    )

    fallback_rate = (
        fallback_count / total
        if total
        else 0
    )

    print(
        "Total records :",
        total
    )

    print(
        "LLM phrases accepted :",
        accepted_count
    )

    print(
        "LLM phrase fallbacks :",
        fallback_count
    )

    print(
        "Fallback rate :",
        f"{fallback_rate:.2%}"
    )

    print(
        "\nIMPORTANT:"
    )

    print(
        "Prediction, confidence, SHAP feature names,"
    )

    print(
        "SHAP feature values, Jaccard, agreement,"
    )

    print(
        "and manual-review wording are deterministic."
    )

    # ========================================================
    # REASON BREAKDOWN
    # ========================================================

    reason_list = []

    for value in (
        results_df[
            "hard_fail_reasons"
        ]
    ):

        if value:

            reason_list.extend(
                [
                    x.strip()
                    for x in value.split(";")
                    if x.strip()
                ]
            )

    if reason_list:

        print(
            "\nLLM phrase failure reasons:"
        )

        counts = (
            pd.Series(
                reason_list
            )
            .value_counts()
        )

        for reason, count in (
            counts.items()
        ):

            print(
                f"  - {reason}: {count}"
            )

    else:

        print(
            "\nNo LLM phrase failures."
        )

    # ========================================================
    # FALLBACK BY AGREEMENT
    # ========================================================

    print(
        "\nFallback rate by agreement category:"
    )

    if total:

        rates = (
            results_df
            .groupby(
                "agreement"
            )[
                "used_fallback"
            ]
            .mean()
        )

        for category, rate in (
            rates.items()
        ):

            print(
                f"  - {category}: "
                f"{rate:.2%}"
            )

    print("=" * 80)

    return results_df


