def clean_output(text):

    if text is None:
        return ""

    text = str(text).strip()

    # Remove common quotation marks
    text = text.strip("\"'`")

    # Remove accidental sentence labels
    text = re.sub(
        r"^\s*(phrase|answer|response|sentence)\s*:\s*",
        "",
        text,
        flags=re.IGNORECASE
    )

    # Remove accidental bullet prefix
    text = re.sub(
        r"^\s*[-*•]\s*",
        "",
        text
    )

    # Normalize whitespace
    text = re.sub(
        r"\s+",
        " ",
        text
    )

    # Remove leading punctuation
    text = text.lstrip(
        " ,;:-"
    )

    # Remove trailing punctuation
    text = text.rstrip(
        ".!?;,: "
    )

    return text.strip()


