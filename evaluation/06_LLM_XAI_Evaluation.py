# 8. BATCH EVALUATION
# ============================================================

def run_batch_eval(
    evidence_records,
    llm,
    max_tokens=200,
    temperature=0.1,
    top_p=0.9,
    sample_size=None
):

    records = (
        evidence_records[:sample_size]
        if sample_size else evidence_records
    )

    results = []

    print("=" * 80)
    print("CONTRIBUTION 3 — FINAL SMOLLM2 BATCH EVALUATION (v5, HYBRID)")
    print("=" * 80)
    print("Records to evaluate:", len(records))
    print("max_tokens:", max_tokens)
    print("temperature:", temperature)
    print("top_p:", top_p)
    print("=" * 80)

    for i, evidence in enumerate(records, start=1):

        start_time = time.time()
        prompt = build_prompt(evidence)

        raw_text = ""
        cleaned_text = ""
        sentences_1_2 = ""
        hard_reasons = []
        soft_warnings = []

        try:
            response = llm.create_chat_completion(
                messages=[
                    {"role": "system", "content": SYSTEM_PROMPT},
                    {"role": "user", "content": prompt},
                ],
                max_tokens=max_tokens,
                temperature=temperature,
                top_p=top_p,
            )

            raw_text = response["choices"][0]["message"]["content"].strip()
            cleaned_text = clean_output(raw_text)

            is_compliant, hard_reasons, soft_warnings = check_compliance(
                cleaned_text, evidence
            )

            if is_compliant:
                sentences_1_2 = cleaned_text
                used_fallback = False
            else:
                sentences_1_2 = build_sentences_1_2_fallback(evidence)
                used_fallback = True

        except Exception as error:
            hard_reasons = [f"generation_error:{str(error)}"]
            sentences_1_2 = build_sentences_1_2_fallback(evidence)
            used_fallback = True

        # Sentence 3 is ALWAYS deterministic -- never at risk.
        sentence_3 = build_sentence_3(evidence)
        final_narrative = sentences_1_2.strip() + " " + sentence_3

        elapsed = time.time() - start_time

        results.append({
            "record_index": i - 1,
            "sample_index": evidence.get("Sample_Index", i - 1),
            "prediction": evidence["Predicted"],
            "confidence": evidence["Confidence"],
            "jaccard": evidence["Jaccard"],
            "agreement": evidence["Agreement"],
            "raw_llm_output": raw_text,
            "post_clean_output": cleaned_text,
            "hard_fail_reasons": "; ".join(hard_reasons),
            "soft_warnings": "; ".join(soft_warnings),
            "used_fallback": used_fallback,
            "final_narrative": final_narrative,
            "generation_time_seconds": round(elapsed, 3),
        })

        status = "FALLBACK" if used_fallback else "LLM OK"
        print(
            f"[{i}/{len(records)}] {status} | "
            f"Sample={evidence.get('Sample_Index', i-1)} | "
            f"Agreement={evidence['Agreement']}"
        )
        if hard_reasons:
            print("    Hard:", hard_reasons)
        if soft_warnings:
            print("    Soft:", soft_warnings)

    results_df = pd.DataFrame(results)

    print("\n" + "=" * 80)
    print("CONTRIBUTION 3 — BATCH SUMMARY (v5)")
    print("=" * 80)

    total = len(results_df)
    fallback_count = int(results_df["used_fallback"].sum())
    accepted_count = total - fallback_count
    fallback_rate = fallback_count / total if total else 0

    print("Total records :", total)
    print("Fallbacks (Sentences 1-2 only) :", fallback_count)
    print("LLM accepted  :", accepted_count)
    print("Fallback rate :", f"{fallback_rate:.2%}")
    print("\nNote: Sentence 3 (Jaccard + agreement + review) is always")
    print("deterministic in v5 and therefore never contributes to fallback.")

    reason_list = []
    for value in results_df["hard_fail_reasons"]:
        if value:
            reason_list.extend([x.strip() for x in value.split(";") if x.strip()])

    if reason_list:
        print("\nHard-fail reason breakdown (Sentences 1-2 only):")
        for reason, count in pd.Series(reason_list).value_counts().items():
            print(f"  - {reason}: {count}")
    else:
        print("\nNo hard-fail reasons triggered.")

    print("\nFallback rate by agreement category:")
    if total:
        rates = results_df.groupby("agreement")["used_fallback"].mean()
        for category, rate in rates.items():
            print(f"  - {category}: {rate:.2%}")

    print("=" * 80)

    return results_df


