# 9. BUILD FINAL SENTENCE 2
# ============================================================

def build_sentence_2(
    evidence,
    llm_phrase
):

    prefix = build_sentence_2_prefix(
        evidence
    )

    phrase = llm_phrase.strip()

    # Remove leading commas if model supplied one
    phrase = phrase.lstrip(
        " ,;:-"
    )

    # Ensure sentence ends naturally
    phrase = phrase.rstrip(
        ".!? "
    )

    return (
        prefix
        + ", "
        + phrase
        + "."
    )


