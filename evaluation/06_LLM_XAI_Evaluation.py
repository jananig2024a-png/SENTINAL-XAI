# 4. DANGEROUS / UNSUPPORTED CLAIMS
# ============================================================

DANGEROUS_PHRASES = [
    "prediction is accurate",
    "prediction was accurate",
    "prediction is correct",
    "prediction was correct",
    "prediction is confirmed",
    "prediction was confirmed",
    "prediction is certain",
    "prediction was certain",
    "prediction is proven",
    "prediction was proven",
    "definitely benign",
    "definitely malicious",
    "confirmed attack",
    "guaranteed",
    "attacker intent",
]


# ============================================================
# 5. DETERMINISTIC SENTENCE 3 BUILDER
#    Always used -- never generated by the LLM.
# ============================================================

def build_sentence_3(evidence):

    jaccard = float(evidence["Jaccard"])
    agreement = str(evidence["Agreement"])
    jaccard_str = f"{jaccard:.4f}"

    if agreement == "high agreement":
        return (
            f"We should note that the SHAP-LIME Jaccard score was "
            f"{jaccard_str}, and SHAP and LIME showed high agreement "
            f"in the explanation."
        )

    if agreement == "low agreement":
        return (
            f"We should note that the SHAP-LIME Jaccard score was "
            f"{jaccard_str}, and SHAP and LIME showed low agreement "
            f"in the explanation, so manual analyst review is recommended."
        )

    return (
        f"We should note that the SHAP-LIME Jaccard score was "
        f"{jaccard_str}, with the supplied agreement category "
        f"'{agreement}'."
    )


# ============================================================
# 6. DETERMINISTIC SENTENCES 1-2 BUILDER (used only if the LLM
#    output for Sentences 1-2 fails compliance)
# ============================================================

def build_sentences_1_2_fallback(evidence):

    prediction = str(evidence["Predicted"])
    confidence = float(evidence["Confidence"])
    top_features = evidence["Top_Features"][:3]

    feature_text = ", ".join(
        [
            f"{f['feature']} ({float(f['value']):.4f})"
            for f in top_features
        ]
    )

    sentence_1 = (
        f"The flow was predicted as {prediction} with a confidence "
        f"of {confidence:.4f}."
    )
    sentence_2 = (
        f"The strongest SHAP-contributing features were {feature_text}."
    )

    return sentence_1 + " " + sentence_2


# ============================================================
# 7. COMPLIANCE GATE FOR SENTENCES 1-2 ONLY
#    (Sentence 3 no longer needs checking -- it's deterministic)
# ============================================================

def check_compliance(text, evidence):

    hard_reasons = []
    soft_warnings = []

    if not text:
        hard_reasons.append("empty_output")
        return False, hard_reasons, soft_warnings

    lower_text = text.lower()

    prediction = str(evidence["Predicted"])
    confidence = float(evidence["Confidence"])
    top_features = evidence["Top_Features"][:3]

    # HARD CHECK 1 — dangerous claims
    for phrase in DANGEROUS_PHRASES:
        if phrase in lower_text:
            hard_reasons.append(f"dangerous_phrase:{phrase}")

    # HARD CHECK 2 — prediction present
    if prediction.lower() not in lower_text:
        hard_reasons.append("missing_prediction")

    # HARD CHECK 3 — confidence preserved
    confidence_str = f"{confidence:.4f}"
    if confidence_str not in text:
        hard_reasons.append("confidence_value_missing_or_altered")

    # HARD CHECK 4 — top-3 SHAP feature names present
    for feature in top_features:
        feature_name = str(feature["feature"]).lower()
        if feature_name not in lower_text:
            hard_reasons.append(f"missing_feature:{feature['feature']}")

    # HARD CHECK 5 — model must not reference agreement/jaccard/review
    # (it wasn't given this info; if it appears, something leaked or
    # the model hallucinated it -- either way, not acceptable)
    leak_terms = ["jaccard", "agreement", "manual review", "manual analyst review"]
    for term in leak_terms:
        if term in lower_text:
            hard_reasons.append(f"unexpected_reference:{term}")

    # SOFT CHECK 1 — sentence count (should be ~2 now)
    normalized = re.sub(r"(?<=[.!?])\s+(?=[A-Z])", "<BOUNDARY>", text.strip())
    sentence_count = len([p for p in normalized.split("<BOUNDARY>") if p.strip()])
    if sentence_count != 2:
        soft_warnings.append(f"sentence_count_{sentence_count}")

    # SOFT CHECK 2 — excessive length
    word_count = len(text.split())
    if word_count > 90:
        soft_warnings.append("output_unusually_long")

    passed = len(hard_reasons) == 0

    return passed, hard_reasons, soft_warnings


