# ============================================================
# 1. SYSTEM PROMPT (v5: scoped to Sentences 1-2 only)
# ============================================================

SYSTEM_PROMPT = """
You are a cybersecurity reporting assistant.

Your job is to convert supplied evidence into two short,
plain-English sentences for a SOC analyst note.

Use only the supplied evidence.
Do not invent facts.
Do not speculate about attacker intent or network behavior.
Do not claim that a prediction is correct, confirmed,
certain, or proven.

Every numerical value given to you (the confidence value) must
appear in your output exactly as given. Never omit it.

Return only the two sentences.
"""


# ============================================================
# 2. PROMPT BUILDER (v5: only prediction, confidence, features
#    are shown to the LLM -- Jaccard and agreement are withheld)
# ============================================================

def build_prompt(evidence):

    prediction = str(evidence["Predicted"])
    confidence = float(evidence["Confidence"])
    confidence_str = f"{confidence:.4f}"

    top_features = evidence["Top_Features"][:3]

    feature_text = "\n".join(
        [
            f"- {f['feature']}: value={float(f['value']):.4f}"
            for f in top_features
        ]
    )

    prompt = f"""
Convert the following evidence into exactly 2 short sentences
for a SOC analyst note.

EVIDENCE

Prediction: {prediction}
Confidence: {confidence_str}

Top SHAP-contributing features:
{feature_text}

OUTPUT INSTRUCTIONS

Sentence 1:
State the predicted class AND the numerical confidence value.
Confidence is MANDATORY. Write it exactly as {confidence_str}.
Do not omit the number. Do not replace it with words such as
"high confidence". Do not write only the predicted class.

Sentence 2:
Name the three supplied top SHAP-contributing features and
their supplied values, calling them "contributing features"
(not causes).

IMPORTANT:
- Use only the supplied evidence above.
- Preserve the confidence value exactly ({confidence_str} must
  literally appear in your output).
- Do not invent network behavior.
- Do not infer causes from the features.
- Do not speculate about attacker intent.
- Do not mention the actual or ground-truth label.
- Do not say the prediction is accurate, correct, confirmed,
  certain, or proven.
- Do not add a heading.
- Do not use bullet points.
- Do not write "Sentence 1", "Sentence 2", etc.
- Do not mention agreement, Jaccard, SHAP-LIME comparison, or
  manual review -- that information is not part of this task.
- Keep it concise and natural, like a SOC analyst note.

Return ONLY the 2 sentences.
"""

    return prompt.strip()


# ============================================================
# 3. CLEAN MODEL OUTPUT
# ============================================================

def clean_output(text):

    if text is None:
        return ""

    text = str(text).strip()
    text = text.replace("**", "")
    text = text.replace("###", "")

    text = re.sub(
        r"^\s*(answer|response|output)\s*:\s*",
        "",
        text,
        flags=re.IGNORECASE
    )

    text = re.sub(
        r"\bSentence\s*[12]\s*:\s*",
        "",
        text,
        flags=re.IGNORECASE
    )

    text = re.sub(r"\s+", " ", text)

    return text.strip()


